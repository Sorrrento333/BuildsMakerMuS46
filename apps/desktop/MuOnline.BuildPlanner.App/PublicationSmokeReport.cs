        BuildDraftDatasetVersion: null,
        BuildDraftDatasetHash: null,
        AppliedMigrationCount: 0,
        AlreadyAppliedMigrationCount: 0,
        ErrorType: exception.GetType().FullName,
        ErrorMessage: exception.Message);
}
